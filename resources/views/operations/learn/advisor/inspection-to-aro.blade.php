    <h3>Advisor conversion workflow</h3>
    <p>Review tech findings in estimate review mode before you present — photos and severity in one pass. See <a href="{{ route('operations.learn.show', ['role' => 'advisor', 'article' => 'estimate-review-mode']) }}">Estimate review mode</a>.</p>
    <p>Build repair actions under the correct scope problem — brakes finding under brake noise scope, not under oil change because that scope was open first.</p>
    <p>Technician guide: <a href="{{ route('operations.learn.show', ['role' => 'technician', 'article' => 'writing-findings']) }}">Writing findings techs advisors trust</a> and <a href="{{ route('operations.learn.show', ['role' => 'technician', 'article' => 'multi-point-inspection']) }}">Multi-point inspection</a>.</p>

    <h3>Present and authorize</h3>
    <p>Present approved and deferred items separately — customers authorize maintenance they understand. Bundling deferred critical safety items into “optional” language is a liability habit, not a sales habit.</p>
    <p>Send portal estimate link when the customer is not at the counter; walk through line-by-line when they are. Same estimate authority either way.</p>
    <p>After authorization, lifecycle moves dispatch the bay — see <a href="{{ route('operations.learn.show', ['role' => 'advisor', 'article' => 'customer-authorization']) }}">Customer authorization</a>.</p>

