    <h3>Inspection findings become revenue</h3>
    <p>A multi-point inspection only pays when findings become scoped recommendations on the estimate. ARK separates <strong>what we saw</strong> from <strong>what we recommend selling</strong> — techs write findings; advisors convert to ARO.</p>
    <p>Each finding should map to a scope problem or a child recommendation under an existing scope — not a junk drawer line at the bottom of the PDF.</p>
    <p>Deferred items are follow-up revenue, not silent omissions. Mark intent honestly so bookend and owner review see real deferred opportunity.</p>

