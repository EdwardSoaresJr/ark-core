    <h3>Why advisors should speak the language</h3>
    <p>Shops that teach the team how a business runs — not only how to turn wrenches — make better decisions at the counter. You do not set labor rate or matrix tiers, but your write-ups, time entries, and follow-through move these numbers.</p>

    <h3>ARO (average repair order)</h3>
    <p>Total posted sales ÷ number of cars in scope. Grows when you:</p>
    <ul>
        <li>Document everything the inspection found — let the customer decide.</li>
        <li>Bundle related work into clear repair actions instead of hiding recommendations.</li>
        <li>Follow deferred scopes instead of assuming “they said no forever.”</li>
    </ul>

    <h3>Effective labor rate (ELR)</h3>
    <p>Labor dollars on posted work ÷ billed hours. It is <em>not</em> the posted rate on the wall — free diag, underpriced menus, and unpaid time dilute ELR.</p>
    <ul>
        <li>Charge diagnostic time per concern when shop policy allows.</li>
        <li>Do not give away inspection labor that should be a priced service.</li>
        <li>Accurate book time and complete tech findings keep labor from leaking.</li>
    </ul>

    <h3>Parts margin</h3>
    <p>The shop targets margin through the parts matrix — automatic sell from cost. Advisors should not negotiate margin away emotionally or override sell without authority.</p>
    <ul>
        <li>Enter real cost when known; matrix applies sell.</li>
        <li>Description is customer-facing — not vendor SKU noise.</li>
        <li>Margin problems are often missed parts lines or habitual discounting — not one bad customer.</li>
    </ul>

    <h3>Sales Posted vs Cash Collected</h3>
    <p>Owners watch both. <strong>Sales Posted</strong> is when the RO is posted after invoice — your margin KPIs use this. <strong>Cash Collected</strong> is payments in the drawer today. Deposits and timing make them differ; you post and collect so reconciliation foots.</p>

    <h3>What you can see in ARK</h3>
    <p>Owners and admins use the Operational Report for daily KPIs. Your operational levers are on the RO: scopes, repair actions, approvals, post, and follow-up — those roll into the numbers they review at Day Review.</p>

