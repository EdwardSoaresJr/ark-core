    <h3>Attrition is normal — growth is not optional</h3>
    <p>Customers die, move, buy new cars, and leave. A healthy shop at real revenue <strong>always needs new clients</strong>. Hearing “we’ve never advertised” often means the shop was underperforming its potential — not that marketing is unnecessary.</p>

    <h3>What this means at the counter</h3>
    <ul>
        <li><strong>Every visit counts.</strong> A rushed intake or weak inspection write-up loses a car you may never see again.</li>
        <li><strong>Write up what the car needs.</strong> Deferred work is follow-up revenue — not failure — but only if the customer understood the recommendation.</li>
        <li><strong>Follow-up is part of the job.</strong> Approvals aging and deferred scopes are tomorrow’s car count, not admin trivia.</li>
    </ul>

    <h3>How the shop measures growth</h3>
    <p>Owners watch <strong>car count</strong> and <strong>ARO</strong> on posted work over time. You do not need to run those reports — but you should know that busy days without posted sales do not count as growth.</p>

    <h3>Marketing truth (for context)</h3>
    <ul>
        <li>No vendor can prove marketing works — only the shop can, by tying spend to car count and ARO over time.</li>
        <li>Give campaigns time, but measure. Paralysis costs more than trying a tool.</li>
        <li>Headroom often lives in <strong>systems</strong> (inspections, pricing discipline, follow-up) before new bays or hires.</li>
    </ul>

