<div class="ops-learn-prose">
    <h3>Parts</h3>
    <ul>
        <li><strong>Description</strong> — customer-facing part name: <em>Radiator</em>, <em>Brake pads</em>. No vendor names or part numbers here.</li>
        <li><strong>Your cost</strong> — what the shop pays.</li>
        <li><strong>Sell</strong> — matrix applies automatically when cost is entered; override only with pricing authority.</li>
        <li><strong>Vendor / part number / sourcing notes</strong> — operational detail for ordering and the team.</li>
    </ul>

    <h3>Labor</h3>
    <ul>
        <li><strong>Hours</strong> — book time or shop standard.</li>
        <li><strong>Labor rate</strong> — shop default unless category or override applies.</li>
        <li><strong>Manual rate override</strong> — requires explicit override when changing sell off the category rate.</li>
        <li>Inside a repair action, labor description usually matches the action title.</li>
    </ul>

    <h3>Notes, sublets, fees</h3>
    <ul>
        <li><strong>Supporting note</strong> — detail tied to one repair action.</li>
        <li><strong>Standalone note</strong> — scope-level only (e.g. further testing required).</li>
        <li><strong>Sublet</strong> — outside work: <em>Alignment at tire shop</em>, <em>Programming at dealer</em>.</li>
        <li><strong>Fee</strong> — shop charge tied to that repair: supplies, hazmat, etc.</li>
    </ul>

    <h3>PartsTech pull quote</h3>
    <ol>
        <li>Create <strong>repair actions with labor</strong> on the scope before pulling the quote.</li>
        <li>Pull quote → assign <strong>scope</strong> and <strong>repair action</strong> per part (or use bulk assign).</li>
        <li>If the scope has one labor-anchored action, parts default there automatically.</li>
        <li>Leave repair action blank only when the part should stay ungrouped at the scope level.</li>
    </ol>
</div>
