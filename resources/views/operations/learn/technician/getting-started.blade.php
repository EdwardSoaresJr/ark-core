    <h3>Your job in ARK</h3>
    <p>Technicians use ARK to find assigned work, read what was sold, and understand job status. You do not build estimates or change pricing.</p>

    <h3>Where to start</h3>
    <ol>
        <li><strong>Workboard</strong> — live lanes show shop pressure. Find jobs in <em>Ready To Dispatch</em>, <em>Active work</em>, or <em>Waiting Parts</em>.</li>
        <li><strong>Repair Orders</strong> — search by RO number, customer, vehicle, VIN, or plate.</li>
        <li><strong>Open the RO</strong> — customer, vehicle, scopes, and approved work are on the worksheet.</li>
    </ol>

    <h3>Assigned technician</h3>
    <p>When you are assigned on an RO, your name appears on the job header. Advisors and managers set assignment — you do not need to change it unless your shop asks you to confirm assignment on open jobs.</p>

    <h3>Tech sheet</h3>
    <p>From the repair order, print or open the <strong>tech sheet</strong> for a bay-friendly view of concerns, findings, and sold work. Use it as the authoritative list of what to perform.</p>

    <h3>What not to do</h3>
    <ul>
        <li>Do not add or edit estimate lines unless your manager has given you advisor permissions.</li>
        <li>Do not change labor rates, parts pricing, or customer-facing totals.</li>
        <li>Use shop process for status changes (in progress, waiting parts, complete) — ask your service team how they want lanes updated in ARK.</li>
    </ul>
</div>
