<div class="ops-learn-prose">
    <h3>Workboard lanes</h3>
    <p>Statuses roll up into lanes on the workboard. Your shop moves jobs forward as work is approved, parts arrive, and bays open.</p>

    <table class="ops-learn-table">
        <thead>
            <tr>
                <th>Lane</th>
                <th>Meaning for techs</th>
            </tr>
        </thead>
        <tbody>
            <tr>
                <td>Check In / Diagnosis</td>
                <td>Still being written or diagnosed — usually not ready for the bay.</td>
            </tr>
            <tr>
                <td>Waiting Approval</td>
                <td>With the customer — do not start billable work until approved.</td>
            </tr>
            <tr>
                <td>Waiting Parts</td>
                <td>Blocked on parts or outside dependency.</td>
            </tr>
            <tr>
                <td>Ready To Dispatch</td>
                <td>Approved and waiting for a bay or assignment.</td>
            </tr>
            <tr>
                <td>Active work</td>
                <td>In the bay now.</td>
            </tr>
            <tr>
                <td>Ready Pickup</td>
                <td>Work complete — customer pickup and payment flow.</td>
            </tr>
        </tbody>
    </table>

    <h3>Practical rule</h3>
    <p>If the job is not in <strong>Ready To Dispatch</strong>, <strong>Active work</strong>, or <strong>Waiting Parts</strong> with advisor clearance, confirm with the service desk before spending shop time on billable repairs.</p>
