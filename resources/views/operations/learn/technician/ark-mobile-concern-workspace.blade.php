    <h3>Concerns are the production surface</h3>
    <p>On ARK Mobile, each <strong>concern</strong> is a workspace — not a row you bounce away from. Open an assigned RO from <strong>My Work</strong>, tap the concern, and stay there while you diagnose, photograph, document, and update production.</p>
    <p>My Work shows a <strong>next action</strong> hint per RO (inspect, document findings, complete scope) so you know what to do beside the vehicle without hunting menus.</p>

    <h3>Inside the concern workspace</h3>
    <ul>
        <li><strong>Customer concern</strong> — what the advisor captured at intake; read-only context.</li>
        <li><strong>Verified findings</strong> — what you confirmed on the vehicle; edit and save in place.</li>
        <li><strong>Recommendation</strong> — advisor-facing sell language; write what you would tell the service writer.</li>
        <li><strong>DTC summary</strong> — codes from check-in OBD or a fresh scan on this concern.</li>
        <li><strong>Photo strip</strong> — capture finding evidence; thumbnails show on the concern; full images sync to ARK inspection authority.</li>
        <li><strong>Production notes</strong> — internal note lines on the concern; not customer-visible portal text.</li>
        <li><strong>Handoff</strong> — flag when the advisor must act (estimate needed, parts unknown, customer decision).</li>
        <li><strong>Complete scope</strong> — when authorized work on this concern is finished, mark production complete from the quick action.</li>
    </ul>

    <h3>Findings and photos</h3>
    <p>Capture photos beside the finding — same discipline as desktop inspection, optimized for one hand and bad signal.</p>
    <p>If connectivity drops, photos queue locally; a pending banner on home reminds you to stay on Wi‑Fi or LTE until upload completes.</p>
    <p>Complete findings with photos before the advisor presents — see <a href="{{ route('operations.learn.show', ['role' => 'technician', 'article' => 'multi-point-inspection']) }}">Multi-point inspection</a> and <a href="{{ route('operations.learn.show', ['role' => 'technician', 'article' => 'writing-findings']) }}">Documenting findings</a>.</p>

    <h3>Production status</h3>
    <p>On approved scopes, update production chips (waiting parts, in progress, complete) from the concern or scope detail. Honest status keeps the workboard and advisor aligned without a walk to the office.</p>
    <p>When all authorized work on a concern is done, use <strong>Complete scope</strong> — the RO projection updates for advisor closeout and next-vehicle rhythm.</p>

    <h3>Comms on assigned work</h3>
    <p>Read conversation context linked to your RO. Internal notes stay in ARK; customer-facing replies remain advisor-owned unless you have broader operations access.</p>

    <h3>What stays on desktop</h3>
    <p>Full estimate builder, PartsTech import, matrix pricing, shop-wide workboard, and deep inspection checklist UI. Mobile records operational truth beside the car; desktop runs the shop.</p>

