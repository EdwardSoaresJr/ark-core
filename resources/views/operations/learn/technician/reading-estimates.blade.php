    <h3>How work is grouped</h3>
    <p>Advisors organize sold work into <strong>repair actions</strong> — one named repair per group, with labor, parts, and notes nested underneath.</p>

    <pre class="ops-learn-code">Replace Water Pump
  Labor — Replace water pump
  Part — Water pump
  Part — Coolant

Replace Drive Belt
  Labor — Replace drive belt
  Part — Serpentine belt</pre>

    <h3>How to read it</h3>
    <ul>
        <li><strong>Repair action title</strong> — the job name. This is what the customer approved.</li>
        <li><strong>Labor line</strong> — the billed operation; hours are the time sold.</li>
        <li><strong>Parts under that action</strong> — components for that repair only.</li>
        <li><strong>Standalone notes</strong> — scope-level instructions outside a specific repair.</li>
    </ul>

    <h3>Older flat estimates</h3>
    <p>Some scopes may still show a flat labor / part list with no repair action headers. Read line descriptions the same way — grouped or flat, the sold work is authoritative.</p>

    <h3>Scope narrative</h3>
    <p>Above the work lines, check <strong>customer states</strong>, <strong>verified findings</strong>, and <strong>recommendation</strong> for context on why the work was sold. Private staff notes may also be present — treat them as advisor-to-tech handoff.</p>
