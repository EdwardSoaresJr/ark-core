    <h3>Weekly owner review (30–45 minutes)</h3>
    <p>ARK steers daily operations. Your accountant owns net profit. This checklist closes the week without dashboard theater.</p>

    <h3>1. Margin Health tab</h3>
    <p>Open <a href="{{ route('operations.reports.operational', ['tab' => 'margin-health']) }}">Operational Report → Margin Health</a> for the week (or month-to-date).</p>
    <ul>
        <li>Which metrics are <strong>amber</strong>? Pick one to fix next week — not all five at once.</li>
        <li>Parts margin below target → review matrix in <a href="{{ route('operations.settings.shop.edit', ['section' => 'financial']) }}">Financial Rules</a>; coach advisors on matrix discipline.</li>
        <li>ELR below posted rate → audit free inspections, oil changes, and unpaid diag time.</li>
        <li>ARO below target → inspection standards and deferred follow-up.</li>
    </ul>

    <h3>2. Production and queue</h3>
    <ul>
        <li>Technician efficiency — who is capacity-constrained vs under-billed?</li>
        <li>Approvals aging and unpaid pickups — cash still on the table?</li>
        <li>Deferred opportunity — what follow-up is scheduled, not just logged?</li>
    </ul>

    <h3>3. Cash vs posted (Financial tab)</h3>
    <p>Open <a href="{{ route('operations.reports.operational', ['tab' => 'financial']) }}">Financial</a> for the week. Reconciliation should foot each day you were open. Persistent gaps mean advisors are collecting without posting — coach the post step on the financial rail.</p>
    <p>Compare ARK <strong>Sales Posted</strong> to your bookkeeper’s revenue for the same period. They should directionally match. Net profit, break-even, and your net-target percent live in P&amp;L — not in RO data alone.</p>

    <h3>4. One implementation commitment</h3>
    <p>Knowledge without implementation is waste. Write down <strong>one</strong> change for next week (e.g. +$5 labor rate, matrix row tune-up, DVI standard). Review it on Monday during your <a href="{{ route('operations.learn.show', ['role' => 'owner', 'article' => 'daily-rhythm']) }}">daily rhythm</a>.</p>

    <h3>5. Update targets quarterly</h3>
    <p>When the shop grows, update <strong>Settings → Owner Targets &amp; Reporting</strong> so report bands stay honest.</p>
