    <h3>Why margins matter</h3>
    <p>Profit is made managing the business through numbers — not by discounting parts or labor to keep customers comfortable. These five steps are the margin levers ARK reinforces in reporting and workflow.</p>

    <h3>Step 1 — Raise posted labor rate</h3>
    <p>Small, consistent increases ($5–10/hr) beat waiting for a crisis. Match cost of living at least once a year. A three-tech shop at 72% productivity can add ~$43k/year from a $10/hr increase alone.</p>
    <p><strong>In ARK:</strong> Shop Settings → labor categories. Compare posted rate to <strong>Effective Labor Rate</strong> on the Operational Report.</p>

    <h3>Step 2 — Follow the parts matrix</h3>
    <p>Target ~55–58% parts margin. The matrix sets sell price — advisors do not negotiate margin away. Review the matrix monthly as average part cost rises.</p>
    <p><strong>In ARK:</strong> Part lines use matrix pricing. Watch <strong>Parts Margin</strong> on Executive Pulse.</p>

    <h3>Step 3 — Better inspections → higher ARO</h3>
    <p>Write up everything the car needs; let the customer decide. General repair ARO benchmark ~$750 for top shops. Even +$50 ARO moves the bottom line without more bays.</p>
    <p><strong>In ARK:</strong> ARO on Executive Pulse; <strong>Deferred Opportunity</strong> for follow-up work.</p>

    <h3>Step 4 — Fix effective labor rate (ELR)</h3>
    <p>ELR = labor dollars collected ÷ billed hours on posted work. Free inspections, cheap oil changes, and unpaid diag time dilute ELR below your posted rate.</p>
    <p><strong>In ARK:</strong> <strong>Effective Labor Rate</strong> KPI — compare to posted rate and your floor target.</p>

    <h3>Step 5 — Workflow and productivity</h3>
    <p>Tech findings must be concise and complete so advisors estimate without chasing techs. Shop-wide +1.5 billed hours/day is meaningful.</p>
    <p><strong>In ARK:</strong> Production tab → technician efficiency. {{ \App\Support\Branding\Branding::learnName() }} advisor guides for repair actions and scopes.</p>

    <h3>Pick one or two</h3>
    <p>Implementation beats knowledge. Choose one step, measure for 30 days, then add the next. See also <a href="{{ route('operations.learn.show', ['role' => 'owner', 'article' => 'daily-kpis']) }}">KPIs to review daily</a>.</p>
