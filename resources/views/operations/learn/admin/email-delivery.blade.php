    <h3>Customer email</h3>
    <p>Official ARK sends production transactional email through <strong>ARK Email</strong> only. Connect it under Settings → Email.</p>
    <p>When ARK Email is not connected, send actions report <em>Email isn’t configured yet</em> — they do not pretend a message was sent.</p>
    <p>Reply-To is your shop address so customers reply directly to the shop. Upstream mail-infrastructure credentials stay on the hosted ARK Email service.</p>

    <h3>Estimate email</h3>
    <p>Estimate email includes the PDF attachment and portal review link when available.</p>
